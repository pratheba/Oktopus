#!/usr/bin/env python3
"""Build a playable Blender timeline from Oktopus 0051 offline pose files.

Run in Blender, not ordinary Python:
  blender -b --python tools/blender_play_0051.py -- --pose-dir /path/to/poses

The 0051 standard `std_handle.npz` is used by the *pose generator*, not by
this viewer. Here the pose_NNN.glb provides static context, `name_NNN.ply`
provides animated vertices, and `skeleton_curve_NNN.npy` the moving centerline.

All imported PLYs must have identical vertex/face ordering: no re-meshing
between pose frames. This is a visual preview, not a deformation simulation.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import bpy
import numpy as np


def cli(argv=None):
    if argv is None:
        argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pose-dir', type=Path, required=True,
                        help='Folder generated by offline_tentacle_motion_0051.py')
    parser.add_argument('--output', type=Path, default=None,
                        help='Output .blend (default: POSE_DIR/animation_0051.blend)')
    parser.add_argument('--fps', type=int, default=24)
    parser.add_argument('--step', type=int, default=6,
                        help='Blender frames between exact poses; 6 at 24 fps = 0.25 s')
    parser.add_argument('--no-static-glb', action='store_true',
                        help='Skip importing the static context from pose_000.glb')
    parser.add_argument('--no-skeleton', action='store_true',
                        help='Hide the moving centerline overlay')
    return parser.parse_args(argv)


def import_ply(path):
    before = set(bpy.data.objects)
    if hasattr(bpy.ops.wm, 'ply_import'):
        bpy.ops.wm.ply_import(filepath=str(path))
    elif hasattr(bpy.ops, 'import_mesh') and hasattr(bpy.ops.import_mesh, 'ply'):
        bpy.ops.import_mesh.ply(filepath=str(path))
    else:
        raise RuntimeError('Blender PLY importer unavailable: enable Import-Export: Stanford PLY')
    imported = [obj for obj in bpy.data.objects if obj not in before and obj.type == 'MESH']
    if len(imported) != 1:
        raise RuntimeError(f'Expected one mesh from {path}, got {len(imported)}')
    return imported[0]


def import_static_scene(path, moving_names):
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=str(path))
    imported = [obj for obj in bpy.data.objects if obj not in before]
    for obj in imported:
        # The 0051 trimesh GLB scene uses node_name and geom_name equal to
        # the `--moving` NAME; Blender may add a .001 suffix.
        if obj.type == 'MESH' and any(obj.name == n or obj.name.startswith(n + '.')
                                      for n in moving_names):
            bpy.data.objects.remove(obj, do_unlink=True)
    print(f'[blender_0051] imported static pose scene: {path}', flush=True)


def mesh_arrays(mesh):
    v = np.empty(len(mesh.vertices) * 3, dtype=np.float32)
    mesh.vertices.foreach_get('co', v)
    idx = np.empty(len(mesh.loops), dtype=np.int32)
    mesh.loops.foreach_get('vertex_index', idx)
    return v.reshape((-1, 3)), idx


def remove_mesh_object(obj):
    data = obj.data
    bpy.data.objects.remove(obj, do_unlink=True)
    if data.users == 0:
        bpy.data.meshes.remove(data)


def add_animated_mesh(pose_dir, name, count, frame_at):
    first_path = pose_dir / f'{name}_000.ply'
    if not first_path.exists():
        raise FileNotFoundError(f'Missing first moving PLY: {first_path}')
    obj = import_ply(first_path)
    obj.name = f'ANIM_{name}'
    obj.data.name = f'{name}_shape_key_geometry'
    base_coords, base_faces = mesh_arrays(obj.data)
    if len(base_faces) == 0 or len(base_coords) == 0:
        raise ValueError(f'{name}: empty PLY')
    obj.shape_key_add(name='Basis', from_mix=False)
    keys = []
    for i in range(1, count):
        pose_path = pose_dir / f'{name}_{i:03d}.ply'
        if not pose_path.exists():
            raise FileNotFoundError(f'Missing mesh frame: {pose_path}')
        imported = import_ply(pose_path)
        coords, faces = mesh_arrays(imported.data)
        try:
            if coords.shape != base_coords.shape or not np.array_equal(faces, base_faces):
                raise ValueError(f'{name}: different vertex/face topology in {pose_path}; '
                                 'cannot animate as a shape key')
            if not np.isfinite(coords).all():
                raise ValueError(f'{name}: nonfinite vertex coordinates in {pose_path}')
            if np.allclose(coords, base_coords, atol=1e-7, rtol=0):
                # Both endpoints of the 0051 sequence are rest pose. No need
                # to allocate another shape-key array for identical geometry.
                keys.append(None)
            else:
                key = obj.shape_key_add(name=f'pose_{i:03d}', from_mix=False)
                key.data.foreach_set('co', coords.astype(np.float32).reshape(-1))
                keys.append(key)
        finally:
            remove_mesh_object(imported)
    # A key is active only at its sampled pose. Linear interpolation between
    # sampled poses gives a smooth preview without re-inferencing the SDF.
    for i in range(count):
        for j, key in enumerate(keys, start=1):
            if key is None:
                continue
            key.value = float(i == j)
            key.keyframe_insert(data_path='value', frame=frame_at(i))
    blocks = obj.data.shape_keys
    if blocks and blocks.animation_data and blocks.animation_data.action:
        action = blocks.animation_data.action
        # Blender 4.4+ layered actions do not expose .fcurves directly.
        for fcurve in getattr(action, 'fcurves', []):
            for kp in fcurve.keyframe_points:
                kp.interpolation = 'LINEAR'
    print(f'[blender_0051] moving {name}: {len(base_coords)} vertices, '
          f'{count} input poses, {sum(k is not None for k in keys)} shape keys', flush=True)
    return obj


def add_animated_skeleton(pose_dir, curve_name, count, frame_at):
    paths = [pose_dir / f'skeleton_{curve_name}_{i:03d}.npy' for i in range(count)]
    if not paths[0].is_file():
        print('[blender_0051] no skeleton NPY poses: skipping overlay', flush=True)
        return None
    if not all(p.is_file() for p in paths):
        raise FileNotFoundError('Skeleton NPY poses are incomplete')
    points = np.asarray(np.load(paths[0], allow_pickle=False), dtype=np.float32)
    if points.ndim != 2 or points.shape[1] != 3 or len(points) < 2:
        raise ValueError('Bad skeleton curve NPY shape')
    mesh = bpy.data.meshes.new(f'skeleton_{curve_name}_polyline')
    mesh.from_pydata(points.tolist(), [(k, k + 1) for k in range(len(points) - 1)], [])
    mesh.update()
    obj = bpy.data.objects.new(f'SKELETON_{curve_name}', mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.display_type = 'WIRE'
    obj.show_wire = True
    obj.show_in_front = True
    obj.hide_render = True
    obj.color = (1.0, 0.67, 0.08, 1.0)
    obj.shape_key_add(name='Basis', from_mix=False)
    keys = []
    for i in range(1, count):
        coords = np.asarray(np.load(paths[i], allow_pickle=False), dtype=np.float32)
        if coords.shape != points.shape or not np.isfinite(coords).all():
            raise ValueError(f'Skeleton topology/values changed in {paths[i]}')
        key = obj.shape_key_add(name=f'skeleton_pose_{i:03d}', from_mix=False)
        key.data.foreach_set('co', coords.reshape(-1))
        keys.append(key)
    for i in range(count):
        for j, key in enumerate(keys, start=1):
            key.value = float(i == j)
            key.keyframe_insert(data_path='value', frame=frame_at(i))
    return obj


def generate(args):
    folder = args.pose_dir.expanduser().resolve()
    manifest_path = folder / 'pose_manifest.json'
    if not manifest_path.is_file():
        raise FileNotFoundError(f'Not a 0051 pose folder: {manifest_path}')
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    names = manifest.get('moving')
    count = int(manifest.get('frames', 0))
    curve = str(manifest.get('curve', ''))
    if not isinstance(names, list) or not names or count < 3:
        raise ValueError('Invalid pose manifest (moving names or frame count)')
    if args.fps <= 0 or args.step < 1:
        raise ValueError('--fps must be positive; --step >= 1')
    expected = [folder / f'pose_{i:03d}.glb' for i in range(count)]
    if not all(p.is_file() for p in expected):
        raise FileNotFoundError('Missing one or more pose_###.glb files')

    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete(use_global=False)
    scene = bpy.context.scene
    scene.frame_start = 1
    scene.frame_end = 1 + (count - 1) * args.step
    scene.render.fps = args.fps
    scene.render.fps_base = 1.0
    sample_frame = lambda i: 1 + i * args.step

    if not args.no_static_glb:
        import_static_scene(folder / 'pose_000.glb', names)
    moving = [add_animated_mesh(folder, name, count, sample_frame) for name in names]
    if not args.no_skeleton:
        add_animated_skeleton(folder, curve, count, sample_frame)

    bpy.ops.object.select_all(action='DESELECT')
    for obj in moving:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = moving[0]
    scene.frame_set(1)
    # Keep Blender ready for solid, interactive viewport playback.
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type == 'VIEW_3D':
                area.spaces.active.shading.type = 'SOLID'
                area.spaces.active.shading.color_type = 'OBJECT'
    output = (args.output or folder / 'animation_0051.blend').expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(output))
    duration = (scene.frame_end - scene.frame_start) / args.fps
    print(f'[blender_0051] READY: {output}', flush=True)
    print(f'[blender_0051] duration={duration:.2f}s fps={args.fps} '
          f'frame_range={scene.frame_start}..{scene.frame_end}; '
          'open in Blender and press SPACE to play', flush=True)
    return output


if __name__ == '__main__':
    generate(cli())
